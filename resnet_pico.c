/* =========================================================================
 * main — interactive console entry point.
 *
 * Flow:
 *   1. Wait for USB serial to connect (up to 5 seconds).
 *   2. Print a welcome banner.
 *   3. Enter an infinite command loop:
 *        - Show a prompt  >
 *        - Read a line from the terminal
 *        - Dispatch the command:
 *            start  -> run inference + print results
 *            info   -> print architecture summary
 *            help   -> print command list
 *            reboot -> watchdog reset
 *        - Unknown commands get a friendly error message.
 *   4. LED blinks at 1 Hz throughout as a heartbeat.
 *
 * Connect with:
 *   Linux/macOS : screen /dev/ttyACM0 115200
 *   Windows     : PuTTY -> Serial -> COMx -> 115200
 * ========================================================================= */
int main(void)
{
#ifdef PICO_BUILD
    stdio_init_all(); /* initialise USB serial (and UART) */

    /*
     * Wait up to 5 seconds for the host to open the serial port.
     * Each iteration is 100 ms, so 50 iterations = 5 seconds.
     * We break early as soon as stdio_usb_connected() returns true.
     */
    for (int i = 0; i < 50; i++) {
        if (stdio_usb_connected()) break;
        sleep_ms(100);
    }

    /* Set up the onboard LED (GPIO 25) for heartbeat blink */
    const uint LED_PIN = 25;
    gpio_init(LED_PIN);
    gpio_set_dir(LED_PIN, GPIO_OUT);
#endif

    /* ------------------------------------------------------------------ */
    /* Welcome banner                                                       */
    /* ------------------------------------------------------------------ */
    printf("\r\n");
    printf("  ========================================\r\n");
    printf("  ResNet MNIST — Raspberry Pi Pico\r\n");
    printf("  ========================================\r\n");
    printf("  Q8.8 fixed-point ResNet-8 inference\r\n");
    printf("  Type  help  to see available commands.\r\n");
    printf("  ========================================\r\n");
    printf("\r\n");

    /*
     * Test image used by the 'start' command.
     * Currently all-zero (blank). Replace with real MNIST pixel data:
     *   - 32x32 pixels, 1 byte per pixel, row-major, greyscale 0-255
     *   - If source is 28x28 MNIST, pad 2 pixels of zeros on each side
     */
    static const uint8_t test_image[INPUT_H * INPUT_W * INPUT_C] = {
        0   /* placeholder — replace with real image bytes */
    };

    /* ------------------------------------------------------------------ */
    /* Command loop — runs forever                                          */
    /* ------------------------------------------------------------------ */
    char cmd_buf[64]; /* buffer for one line of user input */

    while (1) {

#ifdef PICO_BUILD
        /* Heartbeat: toggle LED every half-second while waiting for input */
        gpio_put(LED_PIN, 1);
#endif

        /* Print prompt and read a command */
        printf("> ");
        cmd_read_line(cmd_buf, sizeof(cmd_buf));

#ifdef PICO_BUILD
        gpio_put(LED_PIN, 0);
#endif

        /* ---- Dispatch ------------------------------------------------ */

        if (strcmp(cmd_buf, "start") == 0) {
            /*
             * start — run the full inference pipeline on test_image[].
             * Prints progress markers so you can see which layer is running,
             * then shows the bar chart of all 10 class scores.
             */

            int predicted = resnet_infer_full(test_image);
            print_results(g_logits, predicted);

        } else if (strcmp(cmd_buf, "info") == 0) {
            /*
             * info — print a table of the network architecture and
             * memory usage so you can understand what is running.
             */
            cmd_print_info();

        } else if (strcmp(cmd_buf, "help") == 0 || strcmp(cmd_buf, "?") == 0) {
            /*
             * help / ? — list all available commands.
             */
            cmd_print_help();

        } else if (strcmp(cmd_buf, "reboot") == 0) {
            /*
             * reboot — trigger a watchdog reset to restart the Pico.
             * Useful after flashing new weights without unplugging.
             */
            printf("  Rebooting...\r\n");
#ifdef PICO_BUILD
            watchdog_enable(1, 1); /* 1 ms timeout -> instant reset */
            while (1);             /* wait for watchdog to fire */
#else
            printf("  (reboot not available on host build)\r\n");
#endif

        } else if (cmd_buf[0] == '\0') {
            /* Empty line — just show a new prompt, no error */
            continue;

        } else {
            /* Unknown command */
            printf("  Unknown command: '%s'\r\n", cmd_buf);
            printf("  Type  help  for available commands.\r\n");
            printf("\r\n");
        }
    }

    return 0; /* unreachable but satisfies the compiler */
}
